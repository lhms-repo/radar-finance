/** Returns the icon component for a stored name, falling back to the ellipsis. */
export function categoryIcon(name: string | undefined): LucideIcon {
  return (name && CATEGORY_ICONS[name]) || Ellipsis;
}

/** Renders the icon of a category by its stored name. */
export function CategoryIcon({ name, className }: { name: string | undefined; className?: string }) {
  return createElement(categoryIcon(name), { className });
}
